"use strict";

/* ============================================================
   תרגומי טופס 101 - מילון שטוח בלבד, ללא מבנה מקונן. כל תרגום נופל
   בחזרה לעברית (heFallback) אם השפה הנבחרת היא עברית, או אם המפתח
   עדיין לא קיים במילון של השפה הנבחרת (כך שאפשר למלא את המילון
   בהדרגה, section אחר section, בלי לשבור את המסך באמצע העבודה).
   ר' tr() ב-render.js לפונקציית החיפוש עצמה.

   התוכן עצמו (en/ru) עבר לקובץ i18n.json נפרד שנטען ב-fetch - באותו
   דפוס בדיוק כמו ISRAEL_CITIES/loadCities ב-state.js (ר' שם להסבר
   המלא): לא מוטמע כאן כ-JS literal, כדי שיהיה קובץ נתונים טהור שאפשר
   להחליף בעתיד ב-endpoint אמיתי מהשרת בלי לשנות שורת קוד אחת בטופס.
   FORM101_I18N מתחיל ריק - rawTranslation() כבר בנויה להתמודד עם מילון
   חסר/לא-שלם (מחזירה null, וה-heFallback ב-tr() משמש במקום), כך שאין
   שום סיכון "מסך שבור" בזמן שהתרגומים עדיין בדרך מהרשת. */
let FORM101_I18N = {};
function loadTranslations(){
  fetch("i18n.json")
    .then(function(r){ return r.ok ? r.json() : {}; })
    .then(function(data){ FORM101_I18N = data; if(APP_BOOTED) render(); })
    .catch(function(){ /* אין רשת/הקובץ חסר - הטופס פשוט נשאר בעברית בלבד, לא קריטי */ });
}
loadTranslations();
